import * as fs from 'fs';
import * as path from 'path';
import * as core from '@actions/core';
import { getConfig } from './env';
import { GitHubClient } from './github';
import { buildReleaseContext } from './context';
import { buildPrompt, loadPrompt } from './prompt';
import { writeToRelease } from './publish';
import { resolveRange } from './release';
import { sanitizeNotes } from './sanitize';
import { ChatClient, ModelError, type Usage } from './llm/chat';
import { describeEndpoint } from './llm/endpoint';

/** Write a file to the artifacts directory under the working directory. */
function writeArtifact(name: string, contents: string): void {
  const filePath = path.join(process.cwd(), 'artifacts', name);
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, contents, 'utf8');
}

async function run(): Promise<void> {
  const cfg = getConfig();
  const gh = new GitHubClient(cfg.token, cfg.owner, cfg.repo);
  const client = new ChatClient(cfg.endpoint);

  console.log(`Model: ${describeEndpoint(cfg.endpoint)}`);

  // The prompt comes first, so a prompt-url that can't be fetched fails the run before it reads the release.
  const prompt = await loadPrompt(cfg.promptUrl);
  console.log(`Prompt: ${prompt.source}`);

  const range = await resolveRange(gh, cfg.trigger, cfg.owner, cfg.repo);
  if ('skip' in range) {
    core.notice(range.skip);
    return;
  }

  const context = await buildReleaseContext(cfg, range, gh);
  console.log(`Commit range resolved: ${context.range.totalCommits} commit(s), ${context.linkedItems.length} linked item(s).`);
  if (context.range.totalCommits === 0) {
    core.notice(`There are no commits after ${range.base} up to ${range.head}, so there are no release notes to write.`);
    return;
  }

  const { systemPrompt, userPrompt } = buildPrompt(context, prompt.text);
  const request = { model: cfg.model, systemPrompt, userPrompt };

  // Write the debug artifacts before calling the model so a failed generation still leaves them on disk for a workflow whose upload step runs on failure (e.g. `if: always()`).
  writeArtifact('nuntia-payload.json', JSON.stringify(request, null, 2));
  writeArtifact('nuntia-context.json', JSON.stringify(context, null, 2));

  console.log(`Generating release notes...`);
  const started = Date.now();
  let reply: { text: string } & Usage;
  try {
    reply = await client.generateText(request);
  } catch (err) {
    // Of the provider's failures, only a rejected key, an unknown model or a billing problem fails the run.
    // An outage, a timeout or a bad reply is the provider's problem, and a red run would notify the maintainer about it.
    if (!(err instanceof ModelError) || err.kind === 'fatal') throw err;
    const message = `No release notes were written: ${err.message}`;
    core.warning(message);
    if (process.env.GITHUB_STEP_SUMMARY) await core.summary.addRaw(`${message}\n`).write();
    return;
  }
  const { text, inputTokens, outputTokens } = reply;
  console.log(`Generated in ${((Date.now() - started) / 1000).toFixed(1)}s, using ${inputTokens} input tokens and ${outputTokens} output tokens.`);

  // A preview is cleaned the same way, so it shows what a release would get.
  const notes = sanitizeNotes(text, cfg.owner, cfg.repo).trimEnd();
  if (!notes.trim()) {
    core.warning('Nothing was left of the notes after removing HTML, images and outside links, so there are no release notes to write.');
    return;
  }
  const attribution = '<!-- Do not remove this attribution notice -->\n*These release notes were initially generated by Nuntia. [Learn more](https://github.com/danielchalmers/Nuntia)*';
  const outputText = `${notes}\n\n${attribution}\n`;

  writeArtifact('nuntia-release-notes.md', outputText);

  // Surface the notes in the workflow run summary so they render in the Actions UI without downloading the artifact.
  // Guard on GITHUB_STEP_SUMMARY so local, CLI, and test runs (where the runner variable is absent) don't throw.
  if (process.env.GITHUB_STEP_SUMMARY) {
    await core.summary.addRaw(outputText).write();
    console.log('Wrote release notes to the workflow run summary.');
  }

  if (range.release) await writeToRelease(gh, range.release.tag, outputText);
}

// Exported so tests can wait for the run to finish.
export const finished = run().catch(err => {
  core.setFailed(err instanceof Error ? err.message : String(err));
});
